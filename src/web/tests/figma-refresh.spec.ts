import { test, expect } from '@playwright/test'
import { reset, connect, selectPin } from './helpers'

for (const theme of ['vallum', 'abyssus']) {
  test(`新版工作台合并标题与方案，图例按需展开且保护符号不写设备 ${theme}`, async ({ page }) => {
    await page.setViewportSize({ width: 1366, height: 720 })
    await reset(page)
    await connect(page, 'bus')
    if (theme === 'abyssus') await page.getByRole('button', { name: '切换苍渊' }).click()
    await page.evaluate(() => document.fonts.ready)
    const header = page.locator('.board-workbench-heading')
    expect((await header.boundingBox())!.height).toBe(32)
    const title = await header.getByRole('heading', { name: '设备工作台', exact: true }).boundingBox()
    const input = await page.getByLabel('接线方案名称', { exact: true }).boundingBox()
    expect(Math.abs(title!.y + title!.height / 2 - input!.y - input!.height / 2)).toBeLessThanOrEqual(1)
    const board = page.locator('.board-stage .board-viewport svg.board')
    await expect(board).toHaveAttribute('data-size', 'regular')
    await expect(board.locator('.pin[data-pin-symbol="empty"]')).toHaveCount(25)
    await expect(board.locator('.pin [data-state-icon="lock"]')).toHaveCount(7)
    await expect(board.locator('.pin-protection-hatch')).toHaveCount(0)
    await expect(page.locator('.board-stage > .board-wrap > .board-legend')).toHaveCount(0)
    for (const pin of await board.locator('.pin').all()) {
      await expect(pin).toBeInViewport()
      await expect(pin.locator('.pin-hit')).toHaveAttribute('width', '96')
      await expect(pin.locator('.pin-outline')).toHaveAttribute('width', '86')
    }
    const before = (await (await page.request.get('/api/testing/commands')).json()).commands.length
    const legend = page.locator('.board-stage').getByRole('button', { name: '图例', exact: true })
    await legend.click()
    const dialog = page.getByRole('dialog', { name: '图形含义 · 空闲时不显示图标', exact: true })
    await expect(dialog).toBeVisible()
    const bounds = await dialog.boundingBox()
    expect(bounds!.width).toBe(643)
    expect(bounds!.height).toBe(158)
    await expect(dialog.locator('.pin-state-icon')).toHaveCount(7)
    await page.keyboard.press('Escape')
    await expect(dialog).not.toBeVisible()
    await expect(legend).toBeFocused()
    await selectPin(page, 'R8')
    await expect(page.getByRole('heading', { name: '受保护 · 不可配置', exact: true })).toBeVisible()
    const commands = (await (await page.request.get('/api/testing/commands')).json()).commands.slice(before)
    expect(commands.some((c: { op: string }) => ['resource.open', 'resource.call', 'control.acquire'].includes(c.op))).toBe(false)
  })
}

test('高低电平改变实心空心，翻面后箭头仍相对板子表示输出', async ({ page }) => {
  await page.setViewportSize({ width: 1366, height: 720 })
  await reset(page)
  await connect(page, 'bus')
  await selectPin(page, 'R5')
  await page.locator('.pin-functions').getByRole('button', { name: /^GPIO/ }).click()
  await page.getByRole('button', { name: /^模式：/ }).click()
  await page.locator('.direct-gpio-actions button.primary').click()
  const pin = page.locator('.board-stage .board-viewport [data-pin-id="R5"]')
  await expect(pin).toHaveAttribute('data-pin-symbol', 'high')
  await expect(pin.locator('.pin-state-icon')).toHaveAttribute('data-flipped', 'false')
  await expect(pin.locator('.pin-pad')).toHaveCSS('stroke-width', '1px')
  const color = await pin.locator('.pin-pad').evaluate(node => getComputedStyle(node).fill)
  await page.locator('.direct-gpio-actions button.primary').click()
  await expect(pin).toHaveAttribute('data-pin-symbol', 'low')
  expect(await pin.locator('.pin-pad').evaluate(node => getComputedStyle(node).fill)).toBe(color)
  await page.locator('.board-stage').getByRole('button', { name: '背面', exact: true }).click()
  await expect(pin).toHaveAttribute('data-side', 'left')
  await expect(pin.locator('.pin-state-icon')).toHaveAttribute('data-flipped', 'true')
  await expect(pin).toHaveAttribute('aria-label', /数字输出.*低电平 0/)
})
