import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { reset, connect, selectPin, saveGpio } from './helpers'

async function openConfig(page: import('@playwright/test').Page, kind: 'GPIO' | 'PWM') {
  await selectPin(page, 'R5')
  await page
    .locator('.pin-functions')
    .getByRole('button', { name: new RegExp('^' + kind) })
    .click()
}
test.beforeEach(async ({ page }) => {
  await reset(page)
  await connect(page, 'bus')
})

test('GPIO 单按钮循环、按模式显示，折叠和保存不丢失自定义值', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (e) => errors.push(String(e)))
  const before = (await (await page.request.get('/api/testing/commands')).json()).commands.length
  await openConfig(page, 'GPIO')
  await expect(page.getByLabel('当前引脚')).toHaveText('GPIO10')
  const mode = page.getByRole('button', { name: /^模式：/ })
  await expect(mode).toHaveText('数字输入')
  await expect(page.getByRole('button', { name: /^初始电平：/ })).toHaveCount(0)
  await expect(page.locator('.advanced-config')).not.toHaveAttribute('open')
  await expect(page.getByLabel('接线组名称')).not.toBeVisible()
  await mode.focus()
  await page.keyboard.press('Space')
  const level = page.getByRole('button', { name: /^初始电平：/ })
  await expect(mode).toHaveText('数字输出')
  await page.locator('.advanced-config > summary').click()
  await expect(level).toHaveText('高电平 1')
  await level.click()
  await expect(level).toHaveText('低电平 0')
  await mode.click()
  await expect(mode).toHaveText('开漏输出')
  await page.getByRole('button', { name: /^上下拉：/ }).click()
  await mode.click()
  await expect(mode).toHaveText('数字输入')
  await expect(page.getByRole('button', { name: /^上下拉：/ })).toHaveText('上拉')
  await mode.click()
  await expect(level).toHaveText('低电平 0')
  if ((await page.locator('.advanced-config').getAttribute('open')) === null)
    await page.locator('.advanced-config > summary').click()
  const drive = page.getByRole('button', { name: /^驱动能力：/ })
  await expect(drive).toHaveText('设备默认')
  for (let n = 0; n < 4; n++) await drive.click()
  await expect(drive).toHaveText('档位 3')
  await mode.click()
  await mode.click()
  await mode.click()
  await expect(drive).toHaveText('档位 3')
  const invert = page.getByRole('button', { name: /^反相：/ })
  await invert.click()
  await expect(invert).toHaveText('关闭')
  const edge = page.getByRole('button', { name: /^触发边沿：/ })
  await edge.click()
  await edge.click()
  await page.getByLabel('消抖（μs）', { exact: true }).fill('123')
  await page.locator('.advanced-config > summary').click()
  await saveGpio(page)
  await expect(page.getByRole('button', { name: '保存方案', exact: true })).toBeDisabled()
  await page.reload()
  await page
    .getByRole('navigation')
    .getByRole('button', { name: /^GPIO\d* GPIO · 方案待应用$/ })
    .click()
  await page.locator('.advanced-config > summary').click()
  await expect(page.getByRole('button', { name: /^初始电平：/ })).toHaveText('低电平 0')
  await expect(drive).toHaveText('档位 3')
  await expect(invert).toHaveText('关闭')
  await expect(page.getByLabel('消抖（μs）', { exact: true })).toHaveValue('123')
  expect(errors).toEqual([])
  expect(
    (await (await page.request.get('/api/testing/commands')).json()).commands
      .slice(before)
      .filter((c: { op: string }) => !['state', 'session.ping'].includes(c.op)),
  ).toEqual([])
})

test('PWM 滑杆与精确输入同步，小数和恢复设备默认可保存', async ({ page }) => {
  await openConfig(page, 'PWM')
  const number = page.getByRole('spinbutton', { name: '占空比（%）', exact: true })
  const slider = page.getByRole('slider', { name: '占空比滑杆' })
  await expect(number).toHaveValue('50')
  await expect(page.getByLabel('频率（Hz）', { exact: true })).toHaveValue('1000')
  await number.fill('37.567')
  await expect(slider).toHaveValue('37.567')
  await slider.focus()
  await page.keyboard.press('ArrowRight')
  await expect(number).toHaveValue('38.567')
  await page.keyboard.press('Home')
  await expect(number).toHaveValue('0')
  await page.keyboard.press('End')
  await expect(number).toHaveValue('100')
  await number.fill('37.567')
  await page.getByRole('button', { name: '保存方案', exact: true }).click()
  await expect(page.getByRole('button', { name: '保存方案', exact: true })).toBeDisabled()
  await page.reload()
  await page
    .getByRole('navigation')
    .getByRole('button', { name: /^PWM PWM · 方案待应用$/ })
    .click()
  await expect(number).toHaveValue('37.567')
  await number.fill('')
  await expect(number).toHaveAttribute('placeholder', '设备默认')
  await expect(slider).toHaveAttribute('aria-valuetext', '设备默认')
  await page.locator('.advanced-config > summary').click()
  await expect(page.getByLabel('分辨率（bit）', { exact: true })).toHaveValue('10')
})

test('更换引脚可拒绝保护脚、取消和重新选择', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 900 })
  await openConfig(page, 'GPIO')
  await page.getByRole('button', { name: '更换引脚', exact: true }).click()
  await page.locator('.board-viewport [data-pin-id="R3"]').click()
  await expect(page.locator('.pin-picking-status [role="alert"]')).toContainText('不能承担')
  await page.getByRole('button', { name: '取消更换', exact: true }).click()
  await expect(page.getByLabel('当前引脚')).toHaveText('GPIO10')
  await page.getByRole('button', { name: '更换引脚', exact: true }).click()
  await page.locator('.board-viewport [data-pin-id="R12"]').click()
  await expect(page.getByLabel('当前引脚')).toHaveText('GPIO4')
  await expect(page.getByLabel('接线与调试详情', { exact: true })).toBeFocused()
})

